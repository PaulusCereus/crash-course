# Импортируем модуль requests, который позволяет выполнять HTTP-запросы к веб-сервисам.
import requests
# Импортируем модуль pprint, используемый для "красивого" форматированного вывода сложных структур данных, например, словарей.
import pprint

# Задаём URL API, с которого будем получать данные о случайном пользователе.
URL = "https://randomuser.me/api"

# Отправляем GET-запрос на указанный URL.
# Функция requests.get() возвращает объект response, содержащий статус запроса, заголовки и тело ответа.
response = requests.get(url=URL)

# Проверяем, успешно ли выполнен запрос.
# Атрибут response.ok возвращает True, если HTTP-статус запроса меньше 400 (нет ошибок), иначе — False.
if response.ok:
    # Преобразуем полученные данные из формата JSON в Python-объект (обычно это словарь).
    data = response.json()
    
    # Извлекаем первого пользователя из списка результатов.
    # Ключ "results" содержит список пользователей, даже если он один, поэтому выбираем первый элемент (индекс 0).
    user = data["results"][0]
    
    # Выводим имя пользователя, обращаясь к вложенному словарю 'name' и получая значение по ключу 'first'.
    print(f"Имя: {user['name']['first']}")
    
    # Выводим страну пользователя, обращаясь к вложенному словарю 'location' и получая значение по ключу 'country'.
    print(f"Страна: {user['location']['country']}")
    
    # Выводим строку из 60 символов '-' для визуального разделения блоков информации.
    print("-" * 60)
    
    # Выводим заголовок для раздела, в котором будут показаны все полученные данные.
    print("\nВыводим все данные")
    print("-" * 60)
    
    # Используем pprint для аккуратного форматированного вывода всего словаря data.
    pprint.pprint(data)
    
    # Выводим заголовок для раздела, в котором покажем информацию конкретного пользователя.
    print("\nВыводим пользователя")
    print("-" * 60)
    
    # Снова используем pprint для форматированного вывода словаря user, содержащего данные выбранного пользователя.
    pprint.pprint(user)
else:
    # Если запрос не успешен (например, произошла ошибка соединения или сервер вернул код ошибки),
    # выводим сообщение об ошибке.
    print("Ошибка получения данных")
