# Импортируем библиотеку requests для работы с HTTP-запросами
import requests

def get_joke_types(url):
    """
    Функция для получения списка типов шуток с API.

    Эта функция отправляет GET-запрос к API для получения списка доступных типов шуток.
    Если запрос успешен (статус-код 200), она возвращает список строк, где каждый элемент — это тип шутки.
    Если произошла ошибка (например, проблема с сетью или сервером), функция выводит сообщение об ошибке и возвращает пустой список.

    Параметры:
    - url: str — базовый URL API, к которому добавляется конечная часть "/types".

    Возвращаемое значение:
    - list: список строк, представляющих типы шуток, если запрос успешен.
    - Если произошла ошибка или запрос не дал результатов, возвращается пустой список `[]`.

    Пример:
    >>> get_joke_types("https://official-joke-api.appspot.com/")
    ['programming', 'general', 'knock-knock', 'dad']
    """
    # Отправляем GET-запрос для получения типов шуток
    response = requests.get(f"{url}types")
        # Если статус-код ответа не 200 (ОК)
    if response.status_code != 200:
        # Выводим ошибку, если запрос не успешен
        print("Ошибка при получении типов шуток!")
        # Возвращаем пустой список в случае ошибки
        return []
    # Возвращаем ответ в формате JSON, который содержит список типов шуток
    return response.json()

def get_joke_by_type(url, joke_type):
    """
    Функция для получения случайной шутки по выбранному типу.

    Эта функция отправляет GET-запрос к API для получения случайной шутки по указанному типу.
    Если запрос успешен, возвращает первый элемент из списка шуток в формате JSON, который содержит ключи "setup" и "punchline".
    В случае ошибки или если запрос не вернул данные, функция возвращает `None`.

    Параметры:
    - url: str — базовый URL API, к которому добавляется конечная часть для получения случайной шутки.
    - joke_type: str — тип шутки, выбранный пользователем, например, 'programming', 'general' и т.д.

    Возвращаемое значение:
    - dict или None:
      - Если запрос успешен, возвращается словарь, представляющий шутку, с полями "setup" (вопрос) и "punchline" (ответ).
      - Если запрос не удался или произошла ошибка, возвращается `None`.

    Пример:
    >>> get_joke_by_type("https://official-joke-api.appspot.com/", "programming")
    {'setup': 'Why do programmers prefer dark mode?', 'punchline': 'Because light attracts bugs.'}
    >>> get_joke_by_type("https://official-joke-api.appspot.com/", "nonexistent")
    None
    """
    # Отправляем GET-запрос для получения случайной шутки по типу
    response = requests.get(f"{url}jokes/{joke_type}/random")
        # Если статус-код ответа не 200 (ОК)
    if response.status_code != 200:
        # Выводим ошибку, если запрос не успешен
        print("Ошибка при получении шутки!")
        # Возвращаем None в случае ошибки
        return None
    # Возвращаем первую шутку из ответа в формате JSON (предполагаем, что ответ — это список)
    return response.json()[0]

def display_joke(joke):
    """
    Функция для отображения шутки в консоли.

    Эта функция выводит в консоль текст шутки, состоящий из двух частей: 'setup' и 'punchline'.
    Предполагается, что входной параметр `joke` — это словарь, содержащий шутку с полями "setup" (вопрос) и "punchline" (ответ).

    Параметры:
    - joke: dict — словарь с шуткой, содержащий по крайней мере два ключа: 'setup' и 'punchline'.

    Возвращаемое значение:
    - None — функция ничего не возвращает, она только выводит данные в консоль.

    Пример:
    >>> display_joke({'setup': 'Why do programmers prefer dark mode?', 'punchline': 'Because light attracts bugs.'})
    Сетап: Why do programmers prefer dark mode?
    Панчлайн: Because light attracts bugs.
    """
    # Выводим сетап шутки
    print(f"\nСетап: {joke['setup']}")
    # Выводим панчлайн шутки
    print(f"Панчлайн: {joke['punchline']}\n")
