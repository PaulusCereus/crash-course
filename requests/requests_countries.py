import requests
from prettytable import PrettyTable

def get_country_data(country_name):
    """
    Получает данные о стране из API RestCountries по заданному имени страны.
    
    Параметры:
    country_name (str): Название страны для поиска данных. 
    
    Возвращает:
    dict или None: Возвращает словарь с данными о стране в формате JSON, 
                    если запрос успешен. В случае ошибки возвращает None.
    """
    # Формируем URL для запроса, добавляя название страны в строку запроса
    url = f"https://restcountries.com/v3.1/name/{country_name}"

    try:
        # Выполняем GET-запрос к API
        response = requests.get(url=url)
        # Проверка, что запрос прошел успешно (статус код 200)
        response.raise_for_status()  # Если статус не 200, будет вызвана ошибка
        # Возвращаем данные в формате JSON
        return response.json()
    except requests.exceptions.RequestException as e:
        # В случае ошибки запроса, выводим сообщение и возвращаем None
        print(f"Ошибка при запросе: {e}")
        return None

def extract_country_info(data):
    """
    Извлекает информацию о стране из данных, полученных от API.
    
    Параметры:
    data (dict): Ответ API в формате JSON с данными о странах. Ожидается, 
                 что это список стран, и мы извлекаем данные о первой стране.
    
    Возвращает:
    tuple: Кортеж с информацией о стране:
           (название, столица, регион, население, языки, флаг).
    """
    # Извлекаем данные о первой стране из списка
    country = data[0]  # Ожидаем, что API всегда вернет хотя бы одну страну

    # Безопасное извлечение информации с использованием .get()
    # В случае отсутствия значения возвращаем значение по умолчанию
    name = country.get('name', {}).get('common', 'Неизвестное имя')  # Название страны
    capital = country.get('capital', [None])[0] if country.get('capital') else 'Нет данных'  # Столица
    region = country.get('region', 'Нет данных')  # Регион
    population = country.get('population', 'Нет данных')  # Население
    # Языки: Если языки присутствуют, соединяем их в строку через запятую
    languages = ', '.join(country.get('languages', {}).values()) if country.get('languages') else 'Нет данных'
    # Флаг: Получаем URL изображения флага, если доступен
    flag = country.get('flags', {}).get('png', 'Нет флага')

    # Возвращаем информацию о стране как кортеж
    return (name, capital, region, population, languages, flag)

def get_country_info_table(country_info):
    """
    Создает таблицу с информацией о стране с использованием библиотеки PrettyTable.
    
    Параметры:
    country_info (tuple): Кортеж с данными о стране (название, столица, регион, 
                           население, языки, флаг).
    
    Возвращает:
    PrettyTable: Объект таблицы PrettyTable, который содержит информацию о стране.
    """
    # Создаем объект таблицы
    table = PrettyTable()
    
    # Устанавливаем заголовки столбцов
    table.field_names = ['Страна', 'Столица', 'Регион', 'Население', 'Языки', 'Флаг']
    
    # Добавляем строку с данными о стране
    table.add_row(country_info)

    # Возвращаем готовую таблицу
    return table

def format_population(population):
    """
    Форматирует числовое значение населения с разделением на тысячи.
    
    Параметры:
    population (str или int): Числовое значение населения, переданное как строка или число.
    
    Возвращает:
    str: Отформатированное строковое значение населения с разделением на тысячи, 
         если это возможно. Если значение невозможно преобразовать в число, возвращается строка.
    """
    try:
        # Преобразуем строку в целое число и форматируем с разделением на тысячи
        return f"{int(population):,}"
    except ValueError:
        # Если значение невозможно преобразовать в число, возвращаем исходное значение
        return population
